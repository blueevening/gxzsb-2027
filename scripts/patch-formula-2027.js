function markOut(groupItems, names, suffix) {
  for (const n of names) {
    const it = groupItems.find((x) => x.name === n || x.name.startsWith(n));
    if (!it) {
      console.warn("OUT-目标未找到:", n);
      continue;
    }
    it.out = true;
    if (suffix && !it.name.includes(suffix)) it.name = it.name + suffix;
  }
}

function addAll(group, arr) {
  for (const it of arr) {
    if (group.items.some((x) => x.name === it.name)) {
      console.warn("已存在跳过:", it.name);
      continue;
    }
    group.items.push(it);
  }
}

function findGroup(subj, key) {
  const g = (FB[subj] || []).find((x) => x.key === key);
  if (!g) throw new Error("缺少分组 " + subj + "/" + key);
  return g;
}

